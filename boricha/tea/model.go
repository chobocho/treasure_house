package tea

// Model 은 프로그램의 상태이자 그 상태를 다루는 법이다.
//
// 세 메서드가 전부이고, 셋 다 값 수신자로 쓰라고 만든 것이다.
//
//	Init    프로그램이 시작할 때 딱 한 번. 처음 할 일이 있으면 Cmd 로 돌려준다.
//	Update  사건 하나를 받아 **새 모델** 과 다음에 할 일을 돌려준다.
//	View    지금 상태를 화면 문자열로.
//
// Update 가 모델을 돌려준다는 점이 핵심이다. 포인터로 제자리에서 고치는 것이 아니라
// 고친 복사본을 돌려준다. 그래서 "이 사건이 오면 상태가 이렇게 된다" 를 그대로 시험할 수 있고,
// 화면을 그리는 도중에 다른 고루틴이 상태를 바꿔 놓는 일이 원천적으로 없다.
//
// 대가는 초보자가 반드시 한 번 걸려 넘어지는 함정이다. 값 수신자에 대고 필드를 고친 뒤
// 그 복사본을 돌려주는 것을 잊으면, 그 변경은 조용히 사라진다.
//
// Bubble Tea v2 와 다른 점은 View 뿐이다. 저쪽은 View() View 로 구조체를 돌려주고
// (커서 위치나 배경색 같은 것을 함께 실을 수 있다), 우리는 문자열 하나로 둔다.
// 문자열이면 diff 도 시험도 훨씬 단순해진다.
type Model interface {
	Init() Cmd
	Update(Msg) (Model, Cmd)
	View() string
}
