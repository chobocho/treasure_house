package render

// Diff 는 두 프레임을 견주어 다시 써야 할 줄 번호를 돌려준다.
//
// 왜 줄 단위인가. 칸 단위로 비교하면 바꿔 쓸 바이트는 더 줄지만, 칸마다 커서를 옮기는
// 시퀀스(8바이트 남짓)가 붙어서 오히려 커지기 쉽다. 터미널 화면은 보통 80×24 = 1,920칸,
// 줄로는 24개뿐이다. 줄 하나를 통째로 다시 쓰는 비용이 그 줄 안에서 칸을 골라내는
// 비용보다 싸다. 실제로 Bubble Tea 의 기본 렌더러도 줄 단위다.
//
// 시간 O(줄 수 × 줄 폭) — 문자열 비교가 줄 길이에 비례한다.
// 80×24 화면이면 한 프레임에 2천 바이트쯤 훑는 셈이라, 60 fps 로 돌려도 무시할 수준이다.
// 공간은 바뀐 줄 번호를 담을 슬라이스뿐이다.
func Diff(old, new Frame) []int {
	n := old.Height()
	if new.Height() > n {
		n = new.Height()
	}
	var out []int
	for i := 0; i < n; i++ {
		// 지난 프레임에만 있던 줄은 새 줄이 "" 이므로 여기 걸린다.
		// 그 줄들을 지워 주지 않으면 옛 글이 화면에 유령처럼 남는다.
		if old.Line(i) != new.Line(i) {
			out = append(out, i)
		}
	}
	return out
}
