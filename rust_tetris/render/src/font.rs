/// 글자 폭 5 + 사이 1. 마지막 글자 뒤의 사이는 세지 않는다.
pub fn text_width(s: &str, scale: usize) -> usize {
    let n = s.chars().count();
    if n == 0 { 0 } else { (n * 6 - 1) * scale }
}
