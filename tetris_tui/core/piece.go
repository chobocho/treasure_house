// 왜 이렇게 가르는가. 규칙은 화면과 아무 상관이 없다. 규칙을 화면에서 떼어 놓으면
//   - 터미널 없이 테스트할 수 있고 (실제로 이 패키지의 테스트는 화면을 한 번도 안 그린다)
//   - 1인용·2인용·AI 대전이 같은 규칙을 공유하며
//   - C++ 로 먼저 만든 판(tetris_ai/tetris.cpp)과 한 스텝씩 대조할 수 있다.
//
// 마지막 항목이 이 패키지의 존재 이유다. 이 코드는 새로 지어낸 규칙이 아니라
// C++ 코어의 **이식**이고, test/golden/ 의 골든 트레이스가 그 사실을 증명한다.
// 그래서 상수와 표는 원본에서 그대로 옮겼다 — 다시 유도하지 않았다.
package core

// 판의 크기. 보이는 20줄 위에 숨은 4줄이 있다.
//
// 숨은 줄이 왜 필요한가. 조각은 보이는 판의 맨 윗줄에서 태어나는데(SPAWN_Y = HIDDEN),
// 위쪽으로 두 칸 밀어 올리는 월킥({0,+2})이 존재한다. 여유가 없으면 그 킥이
// 늘 실패해서 SRS 의 손맛이 절반쯤 사라진다. 블록아웃 판정도 이 여유 위에서 이뤄진다.
