// 조각 번호. SHAPES 의 첫 인덱스이자 색 번호 − 1 이다.
const (
	PieceI = iota
	PieceJ
	PieceL
	PieceO
	PieceS
	PieceT
	PieceZ
	PieceCount
)

// PieceNames 는 화면과 로그에 쓰는 이름. 색 순서는 가이드라인을 따른다.
var PieceNames = [PieceCount]string{"I", "J", "L", "O", "S", "T", "Z"}

// 각 조각의 각 회전 상태를 16비트 정수 하나로 표현한다.
// 비트 인덱스 = y*4 + x  (y 는 아래로 증가, x 는 오른쪽으로 증가)
//
//	0x0071 = 0000 0000 0111 0001 → bit0, bit4, bit5, bit6
//
//	  x→ 0 1 2 3
//	y=0  ■ . . .      J 조각의 스폰 상태
//	y=1  ■ ■ ■ .
//	y=2  . . . .
//	y=3  . . . .
//
// 이 표현의 장점: 충돌 검사가 16번의 비트 테스트로 끝나고,
// 조각 데이터 전체가 7×4×2 = 56바이트다. 캐시에 통째로 들어간다.
var Shapes = [PieceCount][4]uint16{
	{0x00F0, 0x2222, 0x0F00, 0x4444}, // I — 하늘색
	{0x0071, 0x0226, 0x0470, 0x0322}, // J — 파랑
	{0x0074, 0x0622, 0x0170, 0x0223}, // L — 주황
	{0x0066, 0x0066, 0x0066, 0x0066}, // O — 노랑 (회전해도 그대로)
	{0x0036, 0x0462, 0x0360, 0x0231}, // S — 초록
	{0x0072, 0x0262, 0x0270, 0x0232}, // T — 보라
	{0x0063, 0x0264, 0x0630, 0x0132}, // Z — 빨강
}

// Blocks 는 (조각, 회전) 의 채워진 칸 넷을 (dx, dy) 로 돌려준다.
// 비트를 직접 훑는 코드가 여러 군데 생기는 걸 막으려고 한 곳에 모았다.
// 반환 배열은 값이라 호출자가 마음대로 써도 안전하다.
//
// O(16) 시간, 할당 없음.
func Blocks(piece, rot int) [4][2]int {
	var out [4][2]int
	n := 0
	m := Shapes[piece][rot&3]
	for i := 0; i < 16; i++ {
		if m&(1<<uint(i)) == 0 {
			continue
		}
		out[n] = [2]int{i & 3, i >> 2}
		n++
	}
	return out
}

// ShapeBottom 은 조각 모양의 가장 아래 행 인덱스(0~3)다. 착지 높이 계산에 쓴다.
func ShapeBottom(piece, rot int) int {
	r := 0
	m := Shapes[piece][rot&3]
	for i := 0; i < 16; i++ {
		if m&(1<<uint(i)) != 0 {
			if y := i >> 2; y > r {
				r = y
			}
		}
	}
	return r
}
