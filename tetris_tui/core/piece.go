	ArrMs     = 40  // 자동반복 1칸당 간격
	SoftDiv   = 20  // 소프트드롭 = 중력의 20배
	LockMs    = 500 // 바닥에 닿은 뒤 굳기까지의 유예
	LockReset = 15  // 유예를 되살릴 수 있는 최대 횟수
