fn main() {
    // 정수끼리 나누면 정수, 실수끼리 나누면 실수다
    println!("7 / 2      = {}", 7 / 2);
    println!("7.0 / 2.0  = {}", 7.0 / 2.0);
    println!("-7 / 2     = {}", -7 / 2);
    println!("-7.0 / 2.0 = {}", -7.0 / 2.0);
    // 나머지도 실수로 나온다
    println!("7.5 % 2.0  = {}", 7.5 % 2.0);

    // 점수 셋의 평균 — 리터럴에 소수점이 있느냐가 가른다
    let total = 70 + 85 + 92;
    println!("정수 평균  = {}", total / 3);
    let total = 70.0 + 85.0 + 92.0;
    println!("실수 평균  = {}", total / 3.0);
    println!("둘째 자리  = {:.2}", total / 3.0);
}
