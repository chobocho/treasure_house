fn main() {
    // 보통 문자열 — 역슬래시는 이스케이프의 시작이다.
    println!("탭\t따옴표\" 역슬래시\\ 줄\n바꿈");
    // 날 문자열 r"…" — 역슬래시를 글자 그대로 둔다.
    println!(r"C:\new\table");
    // 큰따옴표를 넣으려면 # 로 감싼다.
    println!("{}", r#"{"name": "ferris"}"#);
    // 줄 끝의 역슬래시 — 줄바꿈과 다음 줄의 들여쓰기를 삼킨다.
    println!(
        "긴 문장을 \
         두 줄에 나눠 쓴다"
    );
}
