fn main() {
    // 폭 6칸 — 문자열은 왼쪽에, 숫자는 오른쪽에 붙는다
    println!("[{:6}]", "ab");
    println!("[{:6}]", 42);
    // < 왼쪽, ^ 가운데, > 오른쪽
    println!("[{:<6}]", 42);
    println!("[{:^6}]", 42);
    println!("[{:>6}]", "ab");
    // 정렬 기호 앞의 글자 하나가 빈자리를 채운다
    println!("[{:*^6}]", 42);
    println!("[{:->6}]", "ab");
    // 폭보다 긴 값은 자르지 않고 다 찍는다
    println!("[{:2}]", "abcdef");
    // 폭을 변수에서 가져오려면 이름 뒤에 $ 를 붙인다
    let w = 8;
    println!("[{:>w$}]", 42);
    // 폭은 화면 칸이 아니라 글자 수로 센다
    println!("[{:6}]", "한글");
}
