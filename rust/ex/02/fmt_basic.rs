fn main() {
    let lang = "Rust";
    let year = 2015;
    // {} 하나에 인자 하나 — 왼쪽부터 차례로 들어간다
    println!("{} 1.0 은 {} 년에 나왔다", lang, year);
    // 정수·실수·불·문자 모두 {} 로 찍는다
    println!("{} {} {} {}", 42, 2.5, true, 'R');
    // 변수뿐 아니라 식도 인자가 된다
    println!("{} + {} = {}", 2, 3, 2 + 3);
    // 번호를 쓰면 같은 인자를 여러 번, 순서를 바꿔 쓸 수 있다
    println!("{0} 다음은 {1}, {1} 앞은 {0}", "가", "나");
}
