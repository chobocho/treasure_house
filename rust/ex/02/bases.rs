fn main() {
    let n = 255;
    // x 16진수(X 는 대문자), o 8진수, b 2진수
    println!("{:x} {:X} {:o} {:b}", n, n, n, n);
    // # 을 붙이면 0x · 0o · 0b 접두어가 붙는다
    println!("{:#x} {:#o} {:#b}", n, n, n);
    // 0 채움과 폭 8 — 한 바이트를 비트로 본다
    println!("{:08b}", 5);
    // 접두어 두 글자도 폭에 든다 — 0b + 8자리 = 10
    println!("{:#010b}", 5);
    println!("{:#06x}", n);
}
