fn main() {
    let (n, x, s) = (42, 3.14159, "rust");

    println!("[{n}] [{n:5}] [{n:<5}] [{n:^5}] [{n:05}] [{n:+}]");
    println!("[{x}] [{x:.2}] [{x:8.2}] [{x:e}]");
    println!("[{s}] [{s:8}] [{s:>8}] [{s:*^8}] [{s:.2}]");
    println!("[{n:b}] [{n:o}] [{n:x}] [{n:X}] [{n:#x}] [{n:#010b}]");
    println!("[{s:?}] [{:?}] [{:?}]", Some(n), (n, s));
    let (w, p) = (7, 1);
    println!("[{n:w$}] [{x:.p$}] [{x:w$.p$}]");
    println!("[{{}}] [{0} {0} {1}]", n, s);
}
