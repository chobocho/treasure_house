fn main() {
    // 메서드 호출이 단항 - 보다 먼저다.
    println!("{} {}", -2i32.pow(2), (-2i32).pow(2));
    // as 가 나눗셈보다 먼저다.
    println!("{} {}", 10 as f64 / 4 as f64, (10 / 4) as f64);
    // 덧셈이 시프트보다 먼저다.
    println!("{} {}", 1 << 2 + 1, (1 << 2) + 1);
    // 비트 & 가 == 보다 먼저다(C 와 다르다).
    println!("{}", 6 & 3 == 2);
    // && 가 || 보다 먼저다.
    println!("{}", true || false && false);
}
