# -*- coding: utf-8 -*-
"""난수 — 볼랜드 계열 LCG 하나 (SPEC §3).

   짧은 파일이지만 세 언어를 건너는 지점이 둘 있다.
     · 22695477 * s 는 최대 2^56 이라 53비트 가수에 담기지 않는다 → 분할 곱
     · 나머지만 쓰면 모듈로 편향이 생긴다 → 기각 표본추출

   시뮬레이션은 이 인스턴스를 **정확히 하나** 갖는다(SPEC §3.3). 렌더나 UI 가
   난수를 뽑는 순간 두 기계의 수열이 갈리고, 그 뒤로 모든 것이 어긋난다.
"""

A = 22695477
M32 = 4294967296


class LCG(object):
    """상태는 32비트 부호 없는 정수 하나다."""

    def __init__(self, seed):
        self.s = seed % M32
        self.rejects = 0                 # 통계용 — 상태가 아니다

    # ── SPEC §3.1 ──────────────────────────────────────────────────────────
    def next15(self):
        """상태를 한 번 굴리고 상위 15비트(비트 30..16)를 돌려준다.

           하위 비트는 주기가 짧다 — 최하위 비트는 0,1,0,1 을 반복한다.
           그래서 rand() 가 돌려주는 것도 상위 비트다.
        """
        s = self.s
        sh = s // 65536
        sl = s % 65536
        lo = A * sl                      # < 2^41
        hi = (A * sh) % 65536            # < 2^16
        self.s = (lo + hi * 65536 + 1) % M32
        return (self.s // 65536) % 32768

    # ── SPEC §3.2 ──────────────────────────────────────────────────────────
    def roll(self, n):
        """0 <= 결과 < n 인 균등 난수. 기각 루프도 결정론적이다."""
        if n <= 1:
            return 0
        limit = 32768 - 32768 % n
        while True:
            r = self.next15()
            if r < limit:
                return r % n
            self.rejects += 1

    def save(self):
        return self.s

    def load(self, s):
        self.s = s % M32
