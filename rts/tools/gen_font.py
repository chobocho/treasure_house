def rows_of(art):
    """7줄 × 5칸. 정의가 없으면 빈 글자."""
    if not art:
        return ['.....'] * 7
    return [(r + '.....')[:5] for r in art]


def glyph_bytes(ch):
    out = []
    for row in rows_of(G.get(ch)):
        v = 0
        for k in range(5):
            if row[k] == '#':
                v += 1 << (5 - k)              # bit5 가 왼쪽 픽셀
        out.append(v)
    out.append(0)                              # 8번째 줄은 글자 사이 여백
    return out


def main():
    blob = bytearray()
    for code in range(32, 127):
        blob += bytearray(glyph_bytes(chr(code)))
    hexs = ''.join('%02x' % b for b in blob)
    o = ['# SPEC §22.8 6x8 폰트 — ASCII 32..126, 글자당 8바이트 (95자 760바이트)',
         '# 그린 글자 %d자, 나머지는 빈 글자' % len(G),
         hexs]
    io.open(os.path.join(GOLDEN, 'font.txt'), 'w',
            encoding='utf-8').write('\n'.join(o) + '\n')
    print('golden/font.txt — %d바이트, 그린 글자 %d자' % (len(blob), len(G)))
    if '--art' in sys.argv:
        for ch in 'ABCDEFGHIJKLM':
            print(ch)
            for v in glyph_bytes(ch)[:7]:
                print('  ' + ''.join('#' if (v // (1 << (5 - k))) % 2 else '.'
                                     for k in range(6)))


main()
