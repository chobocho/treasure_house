class Comment(unittest.TestCase):
    def test_first_sentence_only(self):
        self.assertEqual(appendix.one_line(['The task id. Second sentence.']), 'The task id.')

    def test_sentence_may_span_lines(self):
        self.assertEqual(appendix.one_line(['Unique id for the', 'task. More.']),
                         'Unique id for the task.')

    def test_markdown_link_keeps_text_and_presence_prefix_goes(self):
        self.assertEqual(appendix.one_line(['Optional. See [RFC 8414](https://x/y) now.']),
                         'See RFC 8414 now.')
        self.assertEqual(appendix.one_line(['Required. The header.']), 'The header.')

    def test_eg_does_not_end_a_sentence(self):
        self.assertEqual(appendix.one_line(['Unique (e.g. UUID) id. Rest.']),
                         'Unique (e.g. UUID) id.')

    def test_long_comment_is_cut(self):
        got = appendix.one_line(['x' * 300])
        self.assertLessEqual(len(got), appendix.MAX_COMMENT)
        self.assertTrue(got.endswith('…'))

    def test_empty(self):
        self.assertEqual(appendix.one_line([]), '')


class Parse(unittest.TestCase):
    def setUp(self):
        self.blocks = appendix.parse_proto(PROTO)
        self.by = {b['name']: b for b in self.blocks}

    def test_blocks_in_file_order_with_kinds(self):
        self.assertEqual([(b['kind'], b['name']) for b in self.blocks],
                         [('service', 'A2AService'), ('message', 'Task'), ('enum', 'Role'),
                          ('message', 'AgentCardSignature'), ('message', 'OAuthFlows')])

    def test_rpcs_with_request_response_and_stream(self):
        rpcs = self.by['A2AService']['items']
        self.assertEqual([(r['name'], r['type'], r['rule']) for r in rpcs],
                         [('SendMessage', 'SendMessageRequest → SendMessageResponse', ''),
                          ('SubscribeToTask', 'SubscribeToTaskRequest → stream StreamResponse', '')])
        self.assertEqual(rpcs[0]['comment'], 'Sends a message to an agent.')

    def test_message_comment_and_fields(self):
        t = self.by['Task']
        self.assertEqual(t['comment'], '`Task` is the core unit of action for A2A.')
        f = {x['name']: x for x in t['items']}
        self.assertEqual(list(f), ['id', 'history', 'history_length', 'metadata', 'reference_task_ids'])
        self.assertEqual((f['id']['type'], f['id']['num'], f['id']['rule']), ('string', '1', 'REQUIRED'))
        self.assertEqual(f['id']['comment'],
                         'Unique identifier (e.g. UUID) for the task, generated by the server for a new task.')
        self.assertEqual(f['history']['type'], 'repeated Message')
        self.assertEqual(f['history']['comment'], 'The history of interactions from a `Task`.')
        self.assertEqual(f['history_length']['type'], 'optional int32')
        self.assertEqual(f['history_length']['comment'], 'The IANA registry name.')
        self.assertEqual(f['metadata']['type'], 'Struct')
        self.assertEqual(f['reference_task_ids']['type'], 'map<string, string>')
        self.assertEqual(f['reference_task_ids']['json'], 'referenceTaskIds')
        self.assertEqual(f['reference_task_ids']['comment'], '')

    def test_enum_values(self):
        r = self.by['Role']
        self.assertEqual([(v['name'], v['num'], v['comment']) for v in r['items']],
                         [('ROLE_UNSPECIFIED', '0', 'The role is unspecified.'),
                          ('ROLE_USER', '1', 'The message is from the client to the server.')])

    def test_linter_block_is_not_a_comment(self):
        f = self.by['AgentCardSignature']['items'][0]
        self.assertEqual((f['name'], f['comment'], f['rule']), ('protected', 'The protected JWS header.', 'REQUIRED'))

    def test_oneof_and_deprecated(self):
        f = self.by['OAuthFlows']['items']
        self.assertEqual([(x['name'], x['oneof'], x['rule']) for x in f],
                         [('client_credentials', 'flow', ''), ('implicit', 'flow', 'DEPRECATED')])


class Rows(unittest.TestCase):
    def test_one_head_row_per_block_then_items(self):
        rows = appendix.field_rows(appendix.parse_proto(PROTO))
        self.assertEqual(rows[0], appendix.HEAD)
        kinds = [(r[0], r[1], r[2]) for r in rows[1:4]]
        self.assertEqual(kinds, [('A2AService', 'service', ''), ('A2AService', 'rpc', 'SendMessage'),
                                 ('A2AService', 'rpc', 'SubscribeToTask')])
        task = [r for r in rows if r[0] == 'Task']
        self.assertEqual(task[0][1], 'message')
        self.assertEqual(task[1], ['Task', 'field', 'id', 'id', 'string', '1', 'REQUIRED', '',
                                   'Unique identifier (e.g. UUID) for the task, generated by the '
                                   'server for a new task.'])
        self.assertTrue(all(len(r) == len(appendix.HEAD) for r in rows))

    def test_tsv_cells_have_no_tab_or_newline(self):
        text = appendix.tsv_text([['a', 'b'], ['x\ty', 'p\nq']])
        self.assertEqual(text, 'a\tb\nx y\tp q\n')


class Vocabulary(unittest.TestCase):
    def test_names_from_proto_rows_and_extra(self):
        rows = appendix.field_rows(appendix.parse_proto(PROTO))
        v = appendix.vocabulary(rows, [['TaskNotFoundError', '오류'], ['A2A-Version', '머리글']])
        self.assertEqual(v['Task'], '메시지')
        self.assertEqual(v['Role'], 'enum')
        self.assertEqual(v['ROLE_USER'], 'enum 값')
        self.assertEqual(v['SendMessage'], '메서드')
        self.assertEqual(v['historyLength'], '필드')
        self.assertEqual(v['TaskNotFoundError'], '오류')
        self.assertEqual(v['A2A-Version'], '머리글')
        self.assertNotIn('history_length', v)          # 와이어 이름(JSON)만 찾는다
        self.assertNotIn('A2AService', v)

    def test_extra_wins_over_proto_kind(self):
        rows = appendix.field_rows(appendix.parse_proto(PROTO))
        v = appendix.vocabulary(rows, [['Task', '특별']])
        self.assertEqual(v['Task'], '특별')


def art(sid, body, cls='card'):
    return '<article class="%s" id="%s">\n%s\n</article>\n' % (cls, sid, body)


class Scan(unittest.TestCase):
    VOCAB = {'Task': '메시지', 'contextId': '필드', 'a<b': '시험'}

    def test_first_slides_in_order_up_to_keep(self):
        secs = [('03_card.html', art('p03-a', '<code>Task</code> <code>Task</code>')
                 + art('p03-b', '<code>contextId</code>')),
                ('04_message.html', art('p04-a', '<code>Task</code>') + art('p04-b', '<code>Task</code>')
                 + art('p04-c', '<code>Task</code>'))]
        got = appendix.scan(secs, self.VOCAB, keep=3)
        self.assertEqual(got, {'Task': ['p03-a', 'p04-a', 'p04-b'], 'contextId': ['p03-b']})

    def test_only_whole_code_spans_quotes_stripped_and_unescaped(self):
        secs = [('05_task.html', art('p05-a', '<code>Task.id</code> Task <code>"contextId"</code>'
                                     ' <code>a&lt;b</code>'))]
        self.assertEqual(appendix.scan(secs, self.VOCAB, keep=3),
                         {'contextId': ['p05-a'], 'a<b': ['p05-a']})

    def test_part_18_is_not_indexed(self):
        secs = [('18_appendix.html', art('p18-a', '<code>Task</code>'))]
        self.assertEqual(appendix.scan(secs, self.VOCAB, keep=3), {})

    def test_pinned_slide_comes_first_and_counts(self):
        secs = [('03_card.html', art('p03-a', '<code>Task</code>') + art('p03-b', '<code>Task</code>')
                 + art('p03-c', '<code>Task</code>'))]
        got = appendix.scan(secs, self.VOCAB, keep=3, pin={'Task': 'p03-c', 'Nope': 'p03-a'})
        self.assertEqual(got, {'Task': ['p03-c', 'p03-a', 'p03-b']})


class Main(unittest.TestCase):
    def setUp(self):
        self.root = tempfile.mkdtemp(prefix='appendix-')
        self.addCleanup(shutil.rmtree, self.root, True)
        self.put('docs/spec/specification/a2a.proto', PROTO)
        self.put('deck/order.txt', '# 순서\n03_card.html\n18_appendix.html\n')
        self.put('deck/sections/03_card.html', art('p03-a', '<code>Task</code> <code>A2A-Version</code>'))
        self.put('deck/sections/18_appendix.html', art('p18', '<code>Task</code>'))
        self.put('deck/index_extra.tsv', 'ident\tkind\nA2A-Version\t머리글\n')
        self.put('deck/proto_where.tsv', 'name\twhere\nRole\tp03-a\n')
        # main 이 찍는 알림은 시험 출력을 어지럽히므로 받아 둔다
        quiet = contextlib.redirect_stdout(io.StringIO())
        quiet.__enter__()
        self.addCleanup(quiet.__exit__, None, None, None)

    def put(self, rel, text):
        p = os.path.join(self.root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w', encoding='utf-8', newline='') as f:
            f.write(text)

    def get(self, rel):
        with open(os.path.join(self.root, rel), encoding='utf-8') as f:
            return f.read()

    def test_writes_fields_and_index(self):
        self.assertEqual(appendix.main([], root=self.root), 0)
        fields = self.get('deck/fields.tsv')
        self.assertTrue(fields.startswith('\t'.join(appendix.HEAD) + '\n'))
        self.assertIn('Task\tfield\tid\tid\tstring\t1\tREQUIRED', fields)
        index = self.get('deck/index.tsv').split('\n')
        self.assertEqual(index[0], 'ident\tkind\twhere')
        self.assertIn('A2A-Version\t머리글\tp03-a', index)
        self.assertIn('Task\t메시지\tp03-a', index)
        self.assertIn('Role\tenum\tp03-a', index)   # 본문에 없어도 손 지도가 가리키면 싣는다

    def test_without_proto_keeps_the_committed_fields(self):
        appendix.main([], root=self.root)
        before = self.get('deck/fields.tsv')
        os.remove(os.path.join(self.root, 'docs/spec/specification/a2a.proto'))
        self.assertEqual(appendix.main([], root=self.root), 0)
        self.assertEqual(self.get('deck/fields.tsv'), before)

    def test_check_reports_stale_without_writing(self):
        self.assertEqual(appendix.main(['--check'], root=self.root), 1)     # 아직 없다
        self.assertFalse(os.path.exists(os.path.join(self.root, 'deck/index.tsv')))
        appendix.main([], root=self.root)
        self.assertEqual(appendix.main(['--check'], root=self.root), 0)
        self.put('deck/sections/03_card.html', art('p03-z', '<code>Task</code>'))
        self.assertEqual(appendix.main(['--check'], root=self.root), 1)


