-- 5x7 비트맵 글꼴 — 파이썬판과 같은 표를 그대로 옮긴다.
-- 한 글자가 7바이트, 각 바이트의 하위 5비트가 한 줄, 최상위 비트가 왼쪽.

local M = {}

M.GLYPHS = {
  [' '] = '00000000000000', ['!'] = '04040404040004', ["'"] = '04040000000000',
  [','] = '0000000000040C', ['-'] = '0000001F000000', ['.'] = '00000000000C0C',
  ['/'] = '01020204080810', [':'] = '000C0C000C0C00', ['<'] = '02040810080402',
  ['>'] = '08040201020408', ['?'] = '0E110102040004', ['('] = '02040808080402',
  [')'] = '08040202020408', ['+'] = '0004041F040400', ['='] = '00001F001F0000',
  ['%'] = '11120404080911', ['#'] = '0A1F0A0A1F0A00', ['*'] = '000A041F040A00',
  ['0'] = '0E11131519110E', ['1'] = '040C040404040E', ['2'] = '0E11010204081F',
  ['3'] = '1F02040201110E', ['4'] = '02060A121F0202', ['5'] = '1F101E0101110E',
  ['6'] = '0608101E11110E', ['7'] = '1F010204080808', ['8'] = '0E11110E11110E',
  ['9'] = '0E11110F01020C',
  A = '0E11111F111111', B = '1E11111E11111E', C = '0E11101010110E',
  D = '1E11111111111E', E = '1F10101E10101F', F = '1F10101E101010',
  G = '0E11101711110F', H = '1111111F111111', I = '0E04040404040E',
  J = '0702020202120C', K = '11121418141211', L = '1010101010101F',
  M = '111B1515111111', N = '11191513111111', O = '0E11111111110E',
  P = '1E11111E101010', Q = '0E11111115120D', R = '1E11111E141211',
  S = '0F10100E01011E', T = '1F040404040404', U = '1111111111110E',
  V = '11111111110A04', W = '1111111515150A', X = '11110A040A1111',
  Y = '11110A04040404', Z = '1F01020408101F',
}

M.FW, M.FH, M.ADV = 5, 7, 6

local ROWS = {}
for ch, hexs in pairs(M.GLYPHS) do
  local t = {}
  for i = 0, M.FH - 1 do
    t[i] = tonumber(hexs:sub(i * 2 + 1, i * 2 + 2), 16)
  end
  ROWS[ch] = t
end

function M.rows(ch)
  return ROWS[ch:upper()] or ROWS[' ']
end

function M.text_width(s) return #s * M.ADV end

return M
