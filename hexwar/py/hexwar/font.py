FW, FH, ADV = 5, 7, 6          # 글자 폭·높이·다음 글자까지의 간격

_ROWS = {}
for _ch, _hexs in GLYPHS.items():
    _ROWS[_ch] = [int(_hexs[i * 2:i * 2 + 2], 16) for i in range(FH)]


def rows(ch):
    """글자 하나의 7줄 비트 패턴. 없는 글자는 공백으로 흘린다."""
    return _ROWS.get(ch.upper(), _ROWS[' '])


def text_width(s):
    return len(s) * ADV
