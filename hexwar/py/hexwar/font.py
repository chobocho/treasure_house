"""5x7 비트맵 글꼴 — SPEC 에는 없지만 화면에 글자를 찍으려면 필요하다.

   도스 게임은 VGA ROM 의 8x8 글꼴을 그냥 썼다(INT 10h 로 주소를 얻어
   ES:BP 에 담아 두는 것이 관용구였다). 한글이 필요하면 별도의 16x16
   조합형/완성형 글꼴 파일을 얹었다 — 그래서 한글 도스 게임의 배포판에는
   HAN.FNT 같은 파일이 딸려 있었다.

   여기서는 외부 자원을 쓸 수 없으므로 5x7 글꼴을 직접 싣는다. 한 글자가
   7바이트, 각 바이트의 하위 5비트가 한 줄이고 최상위 비트가 왼쪽이다.
"""

