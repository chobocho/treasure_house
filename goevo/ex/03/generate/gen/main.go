// 슬라이드 p3-v14-generate — 코드를 만드는 작은 생성기, Go 1.4
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
)

const header = "// 슬라이드 p3-v14-generate — 생성된 파일, Go 1.4"

func main() {
	n := flag.Int("n", 4, "how many squares")
	out := flag.String("o", "", "output file")
	flag.Parse()

	// go generate tells the generator where it was invoked from
	fmt.Printf("gen: GOFILE=%s GOLINE=%s GOPACKAGE=%s\n",
		os.Getenv("GOFILE"), os.Getenv("GOLINE"),
		os.Getenv("GOPACKAGE"))

	var b bytes.Buffer
	fmt.Fprintln(&b, header)
	fmt.Fprintln(&b, "// Code generated by gen; DO NOT EDIT.")
	fmt.Fprintf(&b, "package %s\n", os.Getenv("GOPACKAGE"))
	fmt.Fprintf(&b, "var squares = [...]int{")
	for i := 0; i < *n; i++ {
		fmt.Fprintf(&b, "%d,", i*i)
	}
	fmt.Fprintln(&b, "}")

	src, err := format.Source(b.Bytes()) // gofmt, as a library
	if err == nil {
		err = os.WriteFile(*out, src, 0644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}
